// Writes src/components/settings/brand-icons.ts: the marks of the MCP gallery
// (D-063), copied from simple-icons (CC0, exact version in package.json) so the
// bundle carries only the icons it uses. Run: pnpm --filter @monsters/web icons
import { readFileSync, writeFileSync } from 'node:fs';
import { MCP_CATALOG } from '@monsters/shared';
import * as icons from 'simple-icons';
import { SATURDAY_ICONS } from '../src/components/settings/saturday-icons.ts';
import { brandLight } from '../src/lib/brand-light.ts';

interface SimpleIcon {
  title: string;
  slug: string;
  hex: string;
  path: string;
}

const all = new Map(
  Object.values(icons as unknown as Record<string, SimpleIcon>)
    .filter((i) => typeof i === 'object' && i && 'slug' in i)
    .map((i) => [i.slug, i]),
);

const out: Record<string, { title: string; hex: string; light: string; path: string }> = {};
const missing: string[] = [];
for (const slug of [...new Set(MCP_CATALOG.map((e) => e.icon))].sort()) {
  // Saturday's own marks are drawn by hand (saturday-icons.ts).
  if (SATURDAY_ICONS[slug]) continue;
  const icon = all.get(slug);
  if (!icon) {
    missing.push(slug);
    continue;
  }
  out[slug] = { title: icon.title, hex: icon.hex, light: brandLight(icon.hex), path: icon.path };
}

// The exact version pinned in our package.json (simple-icons does not export its own).
const version = (
  JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')) as {
    devDependencies: Record<string, string>;
  }
).devDependencies['simple-icons'];

const body = `// Generated by scripts/brand-icons.ts from simple-icons ${version} (CC0-1.0,
// https://simpleicons.org). Do not edit: change the catalog and run
// \`pnpm --filter @monsters/web icons\`. Marks are trademarks of their owners,
// used only to show the service a connection goes to.
// Without a mark here (${missing.join(', ')}): a generic icon in the gallery.

export interface BrandIcon {
  title: string;
  /** Colour of the brand. */
  hex: string;
  /** The same colour as light on the black screens (≥ 3:1, brand-light.ts). */
  light: string;
  /** SVG path in a 24×24 box. */
  path: string;
}

export const SIMPLE_ICONS_VERSION = '${version}';

export const BRAND_ICONS: Record<string, BrandIcon> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(new URL('../src/components/settings/brand-icons.ts', import.meta.url), body);
console.warn(`brand-icons.ts: ${Object.keys(out).length} icons, generic for ${missing.join(', ')}`);
