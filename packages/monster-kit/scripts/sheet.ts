/** Shared helpers for the sheet scripts (concept.ts, team.ts). */
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';
import { type Expression, type MonsterGenome, renderMonster } from '../src/index.ts';

export const outDir = resolve(dirname(fileURLToPath(import.meta.url)), '../../../docs/mostri');
export const FONT = "'DejaVu Sans', 'Inter', system-ui, sans-serif";

export const LABELS: Record<Expression, string> = {
  idle: 'idle',
  talk: 'parla',
  think: 'pensa',
  happy: 'fatto / felice',
  error: 'errore',
  sleep: 'dorme',
  confused: 'confuso',
};

const esc = (s: string): string => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');

/** A monster SVG positioned inside a bigger sheet. */
export function place(
  genome: MonsterGenome,
  x: number,
  y: number,
  size: number,
  expression: Expression,
  key: string,
): string {
  const svg = renderMonster(genome, {
    size,
    expression,
    idPrefix: `${key}-${genome.id}-${expression}`,
  });
  return svg.replace('<svg ', `<svg x="${x}" y="${y}" `);
}

export function text(
  x: number,
  y: number,
  s: string,
  opts: { size?: number; weight?: number; fill?: string; anchor?: string } = {},
): string {
  return `<text x="${x}" y="${y}" font-family="${FONT}" font-size="${opts.size ?? 16}" font-weight="${opts.weight ?? 400}" fill="${opts.fill ?? '#2b2733'}" text-anchor="${opts.anchor ?? 'middle'}">${esc(s)}</text>`;
}

export function toPng(svg: string, width: number): Buffer {
  const r = new Resvg(svg, {
    fitTo: { mode: 'width', value: width },
    font: { loadSystemFonts: true, defaultFontFamily: 'DejaVu Sans' },
  });
  return r.render().asPng();
}

/** Standalone HTML page around a sheet; `css` lets the page animate the monsters. */
export function htmlPage(opts: {
  title: string;
  width: number;
  svg: string;
  script: string;
  css?: string;
}): string {
  return `<!doctype html>
<html lang="it">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(opts.title)}</title>
<style>
  html, body { margin: 0; background: #f4f2ee; }
  .sheet { max-width: ${opts.width}px; margin: 0 auto; }
  .sheet > svg { width: 100%; height: auto; display: block; }
</style>${opts.css ? `\n<style>${opts.css}</style>` : ''}
</head>
<body>
<!-- Generated by packages/monster-kit/scripts/${opts.script}: do not edit by hand. -->
<div class="sheet">${opts.svg}</div>
</body>
</html>
`;
}
