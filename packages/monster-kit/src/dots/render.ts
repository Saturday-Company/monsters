import {
  type Expression,
  type MonsterGenome,
  type MonsterGenomeInput,
  parseGenome,
} from '../genome.ts';
import { hashString } from '../random.ts';
import { DOT_H, DOT_W, type DotCell, type DotGrid } from './grid.ts';
import { DOT_GLINT, DOT_OFF, DOT_SCREEN, type DotPalette, dotPalette } from './palette.ts';
import { DOT_FRAMES, buildModel, paintFrame } from './sprite.ts';

/** Distance between two dots, in viewBox units. */
export const DOT_PITCH = 10;
/** Dot radius: LEDs fill 80% of the pitch. */
const R = 4.6;
const PAD = 10;

/** The grid of one frame of one expression. Pure and deterministic. */
export function dotGrid(
  input: MonsterGenome | MonsterGenomeInput,
  expression: Expression = 'idle',
  frame = 0,
): DotGrid {
  return paintFrame(buildModel(parseGenome(input)), expression, frame);
}

/* ------------------------------------------------------------------ timing */

/** One step of an expression's loop: which frame, for how long (ms, before the per-monster tempo). */
type Step = readonly [frame: number, ms: number];

/**
 * Frame loops. Idle has two blink patterns (single, double) picked by the seed; the tempo of each
 * monster (`--dk-t`) stretches every loop and `--dk-phase` shifts it, so neighbours never blink
 * or talk in unison.
 */
export const DOT_TIMELINES: Readonly<Record<string, readonly Step[]>> = {
  'idle-a': [
    [0, 4200],
    [1, 150],
  ],
  'idle-b': [
    [0, 3300],
    [1, 120],
    [0, 170],
    [1, 130],
    [0, 1500],
  ],
  // 0 open, 1 closed, 2 wide: an irregular syllable rhythm with a breath at the end
  talk: [
    [0, 140],
    [2, 180],
    [0, 120],
    [1, 110],
    [2, 200],
    [0, 140],
    [1, 260],
    [0, 130],
    [2, 160],
    [1, 420],
  ],
  think: [
    [0, 520],
    [1, 520],
    [2, 1100],
  ],
  happy: [
    [0, 240],
    [1, 170],
    [0, 200],
    [1, 170],
    [0, 1100],
  ],
  error: [
    [0, 1600],
    [1, 80],
    [0, 90],
    [1, 70],
    [0, 700],
  ],
  sleep: [
    [0, 1100],
    [1, 1100],
    [2, 1300],
  ],
  // looks one way, the other, back, then blinks: unsure where to go next
  confused: [
    [0, 700],
    [1, 620],
    [0, 520],
    [1, 680],
    [2, 140],
  ],
};

const loopName = (expr: Expression, variant: 'a' | 'b'): string =>
  expr === 'idle' ? `idle-${variant}` : expr;

const pct = (v: number): string => `${Math.round(v * 10000) / 100}%`;

function keyframesFor(name: string, steps: readonly Step[], frames: number): string {
  const total = steps.reduce((s, [, ms]) => s + ms, 0);
  const out: string[] = [];
  for (let f = 0; f < frames; f++) {
    const marks: string[] = [];
    let t = 0;
    let prev: boolean | null = null;
    for (const [frame, ms] of steps) {
      const on = frame === f;
      if (on !== prev) marks.push(`${pct(t / total)}{visibility:${on ? 'visible' : 'hidden'}}`);
      prev = on;
      t += ms;
    }
    marks.push(`100%{visibility:${prev ? 'visible' : 'hidden'}}`);
    out.push(`@keyframes dk-${name}-${f}{${marks.join('')}}`);
  }
  return out.join('\n');
}

function buildCss(): string {
  const S = 'svg[data-dots][data-animated="on"]';
  const rules: string[] = [
    '/* Generated by @monsters/monster-kit (dots/render.ts). Frames of the dot monsters. */',
    // frame groups carry visibility="hidden" (all but frame 0) as attributes: without this CSS,
    // or with motion reduced, the first frame is what shows
  ];
  for (const expr of Object.keys(DOT_FRAMES) as Expression[]) {
    const frames = DOT_FRAMES[expr];
    for (const variant of expr === 'idle' ? (['a', 'b'] as const) : (['a'] as const)) {
      const name = loopName(expr, variant);
      const steps = DOT_TIMELINES[name] ?? [];
      const total = steps.reduce((s, [, ms]) => s + ms, 0);
      rules.push(keyframesFor(name, steps, frames));
      const sel = `${S}[data-expression="${expr}"]${expr === 'idle' ? `[data-dk-loop="${variant}"]` : ''}`;
      for (let f = 0; f < frames; f++) {
        rules.push(
          `${sel} [data-frame="${f}"]{animation:dk-${name}-${f} calc(var(--dk-t,1)*${total}ms) step-end calc(var(--dk-phase,0)*-${total}ms*var(--dk-t,1)) infinite}`,
        );
      }
    }
  }
  rules.push(
    '@media (prefers-reduced-motion: reduce){svg[data-dots] [data-frame]{animation:none!important}}',
    '[data-motion="reduced"] svg[data-dots] [data-frame]{animation:none!important}',
  );
  return rules.join('\n');
}

/**
 * Stylesheet that animates `renderDots` output (include once per page). Frames switch with
 * `steps()`-like keyframes on `visibility` only; `data-animated="off"` on the SVG, the
 * `prefers-reduced-motion` query or `data-motion="reduced"` on an ancestor (e.g. `<html>`) leave
 * frame 0.
 */
export const dotCss: string = buildCss();

/* ------------------------------------------------------------------ SVG */

export interface DotRenderOptions {
  expression?: Expression;
  /** Width in px; the height follows the grid (15/17 of it, or the screen's ratio). */
  size?: number;
  /** Accessible name; without it the SVG is decorative (`aria-hidden`). */
  title?: string;
  /** Prefix for ids (only the off-dot pattern uses one). Defaults to a hash of the genome. */
  idPrefix?: string;
  /** Starts the frame loop (with `dotCss`). Default true. All frames are in the SVG either way. */
  animated?: boolean;
  /** Draws only this frame, still. */
  frame?: number;
  /** Draws the black screen (rounded) behind the dots. Default false: the UI draws its own. */
  screen?: boolean;
}

const COLOR_KEYS = [
  'dim',
  'lit',
  'belly',
  'cheek',
  'accentDim',
  'accent',
  'tooth',
  'glint',
] as const;

function colorOf(cell: DotCell, p: DotPalette): string | null {
  switch (cell) {
    case 'lit':
      return p.lit;
    case 'dim':
      return p.dim;
    case 'accent':
      return p.accent;
    case 'accentDim':
      return p.accentDim;
    case 'glint':
      return DOT_GLINT;
    case 'belly':
      return p.belly;
    case 'cheek':
      return p.cheek;
    // teeth are white, like the reflections
    case 'tooth':
      return DOT_GLINT;
    default:
      return null;
  }
}

const cx = (x: number): number => x * DOT_PITCH + DOT_PITCH / 2;

/**
 * Dots as one path per colour: every dot is a zero-length segment with a round cap (`M x y h0`)
 * and a stroke as wide as the dot, so a whole monster is a handful of nodes.
 */
function dotsPath(cells: [number, number][], color: string, r = R): string {
  if (cells.length === 0) return '';
  let d = '';
  for (const [x, y] of cells) d += `M${cx(x)} ${cx(y)}h0`;
  return `<path d="${d}" stroke="${color}" stroke-width="${r * 2}" stroke-linecap="round"/>`;
}

function frameGroup(grid: DotGrid, p: DotPalette, index: number | null): string {
  const by = new Map<string, [number, number][]>();
  for (let y = 0; y < grid.height; y++)
    for (let x = 0; x < grid.width; x++) {
      const cell = grid.cells[y * grid.width + x] ?? 'off';
      if (!colorOf(cell, p)) continue;
      const list = by.get(cell) ?? [];
      list.push([x, y]);
      by.set(cell, list);
    }
  let body = '';
  for (const k of COLOR_KEYS) {
    const color = colorOf(k, p);
    const cells = by.get(k);
    if (color && cells) body += dotsPath(cells, color);
  }
  const attrs: string[] = [];
  if (index !== null) attrs.push(`data-frame="${index}"`);
  if (index !== null && index > 0) attrs.push('visibility="hidden"');
  if (grid.light < 1) attrs.push(`opacity="${grid.light}"`);
  return `<g${attrs.length ? ' ' + attrs.join(' ') : ''}>${body}</g>`;
}

const escapeXml = (s: string): string =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const f3 = (n: number): string => String(Math.round(n * 1000) / 1000);

/** Per-monster tempo and phase from the seed (and personality.speed). */
export function dotRhythm(g: MonsterGenome): { tempo: number; phase: number; loop: 'a' | 'b' } {
  const h1 = hashString(`${g.id}:${g.seed}:tempo`) / 4294967296;
  const h2 = hashString(`${g.id}:${g.seed}:phase`) / 4294967296;
  const h3 = hashString(`${g.id}:${g.seed}:blink`) / 4294967296;
  const tempo = (0.82 + 0.4 * h1) * (1.15 - 0.3 * g.personality.speed);
  return {
    tempo: Math.round(tempo * 1000) / 1000,
    phase: Math.round(h2 * 1000) / 1000,
    loop: h3 < 0.55 ? 'a' : 'b',
  };
}

/** The monster as luminous dots on a black LED screen, all frames of one expression in one SVG. */
export function renderDots(
  input: MonsterGenome | MonsterGenomeInput,
  opts: DotRenderOptions = {},
): string {
  const g = parseGenome(input);
  const expr: Expression = opts.expression ?? 'idle';
  const model = buildModel(g);
  const p = dotPalette(g);
  const screen = opts.screen ?? false;
  const pad = screen ? PAD : 0;
  const vbW = DOT_W * DOT_PITCH + 2 * pad;
  const vbH = DOT_H * DOT_PITCH + 2 * pad;
  const width = opts.size ?? vbW;
  const height = (width * vbH) / vbW;
  const prefix = opts.idPrefix ?? `d${hashString(`${g.id}:${g.seed}:${expr}`).toString(36)}`;
  const still = opts.frame !== undefined;
  const animated = !still && (opts.animated ?? true);
  const rhythm = dotRhythm(g);

  const frames: string[] = [];
  if (still) frames.push(frameGroup(paintFrame(model, expr, opts.frame ?? 0), p, null));
  else
    for (let f = 0; f < DOT_FRAMES[expr]; f++)
      frames.push(frameGroup(paintFrame(model, expr, f), p, f));

  const offId = `${prefix}-off`;
  const parts = [
    screen
      ? `<rect x="${-pad}" y="${-pad}" width="${vbW}" height="${vbH}" rx="14" fill="${DOT_SCREEN}"/>`
      : '',
    `<defs><pattern id="${offId}" width="${DOT_PITCH}" height="${DOT_PITCH}" patternUnits="userSpaceOnUse"><circle cx="${DOT_PITCH / 2}" cy="${DOT_PITCH / 2}" r="${R}" fill="${DOT_OFF}"/></pattern></defs>`,
    `<rect width="${DOT_W * DOT_PITCH}" height="${DOT_H * DOT_PITCH}" fill="url(#${offId})"/>`,
    ...frames,
  ];
  const title = opts.title ? escapeXml(opts.title) : '';
  const a11y = title ? `role="img" aria-label="${title}"` : 'aria-hidden="true"';
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-pad} ${-pad} ${vbW} ${vbH}" width="${f3(width)}" height="${f3(height)}" ${a11y} data-dots="${escapeXml(g.id)}" data-expression="${expr}" data-animated="${animated ? 'on' : 'off'}" data-dk-loop="${rhythm.loop}" style="--dk-t:${rhythm.tempo};--dk-phase:${rhythm.phase}">` +
    (title ? `<title>${title}</title>` : '') +
    parts.join('') +
    '</svg>'
  );
}
